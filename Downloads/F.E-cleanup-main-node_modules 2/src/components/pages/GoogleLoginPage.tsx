import React, { useEffect } from 'react';

declare global {
  interface Window {
    google: any;
  }
}

type GoogleLoginPageProps = {
  onClick?: () => void;
};

const GoogleLoginPage: React.FC<GoogleLoginPageProps> = ({ onClick }) => {
  const handleCredentialResponse = async (response: any) => {
    const token = response.credential;
  
    // 예: 로컬 스토리지 저장
    localStorage.setItem("googleIdToken", token);
  };

  useEffect(() => {
    if (window.google) {
      window.google.accounts.id.initialize({
        client_id: '455479613011-ri3ju46n6vl3pm8856bdj5emnohjt81a.apps.googleusercontent.com',
        callback: handleCredentialResponse,
        auto_select: false,
        use_fedcm_for_prompt: false,
      });
    }
  }, []);

  const handleGoogleLogin = () => {
    window.google.accounts.id.prompt();
    if (onClick) {
      onClick();
    }
  };

  return (
    <button
      onClick={handleGoogleLogin}
      style={{ background: 'transparent', border: 'none', cursor: 'pointer' }}
    >
      <img src="/images/login/google_login.png" alt="Google login" style={{ width: '100px', height: '25px' }} />
    </button>
  );
};

export default GoogleLoginPage;