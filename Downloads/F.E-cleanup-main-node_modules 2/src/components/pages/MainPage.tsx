import React, { useState, useEffect, useCallback } from "react";
import "../pages/MainPage.css";
import FilterModal from "../modals/FilterModal";
import CreateRoomModal from "../modals/CreateRoomModal";
import ApprovalRequestModal from "../modals/ApprovalRequestModal";
import axios from "axios";

interface GetRoomsResponse {
  isSuccess: boolean;
  data: {
    studyGroups: RoomData[];
    totalPages: number;
    totalElements: number;
    currentPage: number;
    pageSize: number;
  };
}

export interface RoomData {
  id: number;
  roomName: string;
  imageUrl?: string;
  capacity: number | string;
  purpose?: string;
  region?: string;
  introduction?: string;
}


const fallbackImages = [
  "/images/mainpage/1.jpg",
  "/images/mainpage/2.jpg",
  "/images/mainpage/3.jpg",
  "/images/mainpage/4.jpg",
  "/images/mainpage/5.jpg",
  "/images/mainpage/6.jpg",
];

const getRandomDefaultImage = () => {
  const index = Math.floor(Math.random() * fallbackImages.length);
  return fallbackImages[index];
};

const assignRandomImages = (rooms: RoomData[]) => {
  let index = 0;
  return rooms.map((room) => {
    const hasValidImage = room.imageUrl && room.imageUrl.trim() !== "";
    return {
      ...room,
      imageUrl: hasValidImage ? room.imageUrl : fallbackImages[index++ % fallbackImages.length],
    };
  });
};

function MainPage() {
  const [isFilterOpen, setIsFilterOpen] = useState(false);
  const [isCreateModalOpen, setIsCreateModalOpen] = useState(false);
  const [isApprovalModalOpen, setIsApprovalModalOpen] = useState(false);
  const [selectedRoom, setSelectedRoom] = useState<RoomData | null>(null);
  const [studyRooms, setStudyRooms] = useState<RoomData[]>([]);
  const [currentPage, setCurrentPage] = useState(1);
  const roomsPerPage = 6;
  const [searchQuery, setSearchQuery] = useState("");
  const [filteredRooms, setFilteredRooms] = useState<RoomData[] | null>(null);

  // 전체 스터디방 목록 조회
  const fetchStudyRooms = useCallback(async () => {
    try {
      const response = await axios.get<GetRoomsResponse>(
        `http://34.22.72.174:8080/api/v1/board?page=0&size=55`,
        { withCredentials: true }
      );
      if (response.data.isSuccess) {
        const assignedRooms = assignRandomImages(response.data.data.studyGroups);
        setStudyRooms(assignedRooms);
      }
    } catch (error) {
      console.error("스터디방 목록을 불러오는데 실패했습니다:", error);
    }
  }, []);

  // 단일 스터디방 상세 조회
  const fetchRoomDetail = async (roomId: number, fallbackImageUrl?: string) => {
    try {
      const response = await axios.get<{ isSuccess: boolean; data: RoomData }>(
        `http://34.22.72.174:8080/api/v1/board/${roomId}`,
        { withCredentials: true }
      );
  
      if (response.data.isSuccess) {
        const roomData = response.data.data;
  
        // ✅ 메인에서 본 이미지로 덮어쓰기
        const mergedRoomData = {
          ...roomData,
          imageUrl: roomData.imageUrl || fallbackImageUrl || getRandomDefaultImage(),
        };
  
        setSelectedRoom(mergedRoomData);
        setIsApprovalModalOpen(true);
      }
    } catch (error) {
      console.error("스터디방 상세 정보를 불러오는데 실패했습니다:", error);
    }
  };  

  useEffect(() => {
    fetchStudyRooms();
  }, [fetchStudyRooms]);

  useEffect(() => {
    if (filteredRooms && filteredRooms.length === 0) {
      const timeout = setTimeout(() => {
        setFilteredRooms(null); // 다시 전체 목록 보여주기
      }, 5000);
  
      return () => clearTimeout(timeout); // cleanup
    }
  }, [filteredRooms]);  

  // 보여줄 방 목록: 필터된게 있으면 그걸, 없으면 전체
  const roomsToShow = filteredRooms !== null ? filteredRooms : studyRooms;

  // 페이지네이션 인덱스 계산
  const startIndex = (currentPage - 1) * roomsPerPage;
  const endIndex = startIndex + roomsPerPage;
  const paginatedRooms = roomsToShow.slice(startIndex, endIndex);
  const totalPages = Math.ceil(roomsToShow.length / roomsPerPage);

  // 방 생성 후 목록 새로고침 (onCreateSuccess 콜백)
  const handleCreateSuccess = async (newRoomData: RoomData) => {
    setIsCreateModalOpen(false);
    // API에서 최신 목록 다시 불러오기
    await fetchStudyRooms();
    setStudyRooms((prevRooms) => [newRoomData, ...prevRooms]);
    setFilteredRooms(null);
    setCurrentPage(1);  // 1페이지로 이동 (새로 만든 방이 보이도록)
  };

  // 검색 제출 시
  const onSearchSubmit = (e: React.FormEvent<HTMLFormElement>) => {
    e.preventDefault();
  
    const trimmedQuery = searchQuery.trim().toLowerCase();
  
    const matchedRooms = studyRooms.filter((room) =>
      room.roomName.toLowerCase().includes(trimmedQuery)
    );
  
    setSearchQuery(""); // 인풋 초기화
  
    if (matchedRooms.length > 0) {
      setFilteredRooms(matchedRooms);
      setCurrentPage(1);
  
      // 15초 후 다시 전체 목록 보여주기
      setTimeout(() => {
        setFilteredRooms(null);
      }, 5000);
  
    } else {
      setFilteredRooms([]); // 빈 배열 → "존재하는 스터디방이 없습니다."
      setCurrentPage(1);
  
      setTimeout(() => {
        setFilteredRooms(null);
      }, 5000);
    }
  };  

  return (
    <div>
      <div className="main-box">
        <form className="main-search" onSubmit={onSearchSubmit}>
          <div className="search-wrapper">
            <input
              className="search-txt"
              type="text"
              placeholder="스터디방 이름 또는 카테고리를 입력하세요."
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
            />
            <button type="submit" className="main-search-btn" aria-label="검색" />
          </div>
        </form>
      </div>

      <div className="main-button">
        <button className="main-filter" onClick={() => setIsFilterOpen(true)}>
          필터
        </button>
        <div className="main-createroom" onClick={() => setIsCreateModalOpen(true)}>
          방 생성
        </div>
      </div>

      <div className="grid-container">
        {paginatedRooms.length === 0 ? (
          <div className="no-rooms-message">존재하는 스터디방이 없습니다.</div>
        ) : (
          paginatedRooms.map((room) => (
            <div
              key={room.id}
              className="grid-room"
              role="button"
              tabIndex={0}
              onClick={() => fetchRoomDetail(room.id, room.imageUrl)}
            >
              <img
                src={room.imageUrl || getRandomDefaultImage()}
                alt="스터디 이미지"
                className="room-profile-img"
                onError={(e) => {
                  e.currentTarget.src = getRandomDefaultImage();
                }}
              />
              <div className="room-label">{room.roomName}</div>
            </div>
          ))
        )}
      </div>

      {/* 페이지네이션 */}
      {totalPages > 1 && (
        <div className="pagination">
          <button
            onClick={() => setCurrentPage((prev) => Math.max(prev - 1, 1))}
            disabled={currentPage === 1}
          >
            이전
          </button>
          {[...Array(totalPages)].map((_, idx) => (
            <button
              key={idx}
              className={currentPage === idx + 1 ? "active" : ""}
              onClick={() => setCurrentPage(idx + 1)}
            >
              {idx + 1}
            </button>
          ))}
          <button
            onClick={() => setCurrentPage((prev) => Math.min(prev + 1, totalPages))}
            disabled={currentPage === totalPages}
          >
            다음
          </button>
        </div>
      )}

      <FilterModal
        isOpen={isFilterOpen}
        onClose={() => setIsFilterOpen(false)}
        onApplyFilter={() => {
          setIsFilterOpen(false);
        }}
      />

      <CreateRoomModal
        isOpen={isCreateModalOpen}
        onClose={() => setIsCreateModalOpen(false)}
        onCreateSuccess={handleCreateSuccess}
      />

      <ApprovalRequestModal
        isOpen={isApprovalModalOpen}
        onClose={() => setIsApprovalModalOpen(false)}
        room={
          selectedRoom && {
            id: selectedRoom.id,
            title: selectedRoom.roomName,
            image: selectedRoom.imageUrl || getRandomDefaultImage(),
            capacity: String(selectedRoom.capacity),
            purpose: selectedRoom.purpose ?? "",
            region: selectedRoom.region ?? "",
            description: selectedRoom.introduction ?? "",
          }
        }
        currentUser={null}
      />
    </div>
  );
}

export default MainPage;