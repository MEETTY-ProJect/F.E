import React, { useEffect } from "react";
import "./KakaoLoginButton.css";

declare global {
  interface Window {
    Kakao: any;
  }
}

function KakaoLoginButton() {
  useEffect(() => {
    if (window.Kakao && !window.Kakao.isInitialized()) {
      window.Kakao.init(import.meta.env.VITE_KAKAO_JS_KEY as string);
    }
  }, []);

  const handleLogin = () => {
    if (!window.Kakao) {
      alert("카카오 SDK가 로드되지 않았습니다. 페이지를 새로 고침해주세요.");
      return;
    }
    if (!window.Kakao.isInitialized()) {
      alert("카카오 SDK가 초기화되지 않았습니다.");
      return;
    }

    window.Kakao.Auth.login({
      success(authObj: any) {
        console.log("카카오 로그인 성공:", authObj);
        // ✅ access_token을 백엔드로 전달
        fetch("https://your-backend/api/auth/kakao", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ accessToken: authObj.access_token }),
        })
          .then((res) => res.json())
          .then((data) => {
            // 로그인 성공 후 로직
            console.log(data);
            // 예: 로컬 스토리지 저장 후 페이지 이동
            alert("카카오 로그인 성공");
          })
          .catch((error) => {
            console.error(error);
            alert("서버 로그인 실패");
          });
      },
      fail(error: any) {
        console.error(error);
        alert("카카오 로그인 실패: 다시 시도해주세요.");
      },
    });
  };
  
  return (
    <button className="kakao-login-button" onClick={handleLogin}>
      <img
        src="/images/login/kakao_login.png"
        alt="Kakao symbol"
        className="kakao-login-icon"
      />
    </button>
  );
}

export default KakaoLoginButton;