import React, { useState, useEffect } from "react";
import axios from "axios";

interface ApprovalRequestModalProps {
  isOpen: boolean;
  onClose: () => void;
  room: {
    id: number;
    title: string;
    image: string;
    capacity: string;
    purpose: string;
    region: string;
    description: string;
  } | null;
  currentUser: {
    id: number;
  } | null;
  onRequestSuccess?: () => void;
}

interface ApprovalResponse {
  isSuccess: boolean;
  data: string;
  errorCode: object;
}

const ApprovalRequestModal: React.FC<ApprovalRequestModalProps> = ({
  isOpen,
  onClose,
  room,
  onRequestSuccess,
}) => {
  const [displayPurpose, setDisplayPurpose] = useState("");
  const [displayRegion, setDisplayRegion] = useState("");
  const [displayMaxPeople, setDisplayMaxPeople] = useState(0);
  const [loading, setLoading] = useState(false);
  const [showSuccessModal, setShowSuccessModal] = useState(false);

  useEffect(() => {
    if (room) {
      setDisplayPurpose(room.purpose || "");
      setDisplayRegion(room.region || "");
      setDisplayMaxPeople(parseInt(room. capacity, 10) || 0);
    }
  }, [room]);
  
  useEffect(() => {
    if (room) {
      console.log("✅ 모달에 전달된 이미지 URL:", room.image);
    }
  }, [room]);  

  const handleApprovalRequest = async () => {
    const token = localStorage.getItem("accessToken"); 
    if (!token) {
      alert("로그인 후 이용해주세요.");
      return;
    }
    if (!room?.id) {
      alert("방 정보를 찾을 수 없습니다.");
      return;
    }

    setLoading(true);

    try {
      const response = await axios.post<ApprovalResponse>(
        `http://34.22.72.174:8080/api/v1/board/${room.id}/join`,
        {},
        {
          headers: {
            Accept: "*/*",
            Authorization: `Bearer ${token}`
          },
          withCredentials: true,
        }
      );
      if (response.data.isSuccess) {
        if (onRequestSuccess) {
          onRequestSuccess();
        }
        onClose(); // 원래 열려 있던 승인 요청 모달 닫힘
        setShowSuccessModal(true); // 성공 메시지 모달로 뜸
      } else {
        alert("승인 요청에 실패했습니다.");
        console.error("ErrorCode:", response.data.errorCode);
      }
    } catch (error) {
      alert("승인 요청 실패");
      console.error(error);
    } finally {
      setLoading(false);
    }
  };
  
  if (!isOpen || !room) return null;

  return (
    <>
      <div className="approval-overlay" onClick={onClose}>
        <div
          className="approval-modal-content"
          onClick={(e) => e.stopPropagation()}
        >
          <div style={{ position: "relative", width: "450px", height: "150px" }}>
          <img
          src={room.image || "/images/default-room.jpg"}
          alt={room.title}
          style={{
            width: "100%",
            height: "100%",
            objectFit: "cover",
            borderTopLeftRadius: "15px",
            borderTopRightRadius: "15px",
            }}
            />
            <p
              style={{
                position: "absolute",
                top: "50%",
                left: "50%",
                transform: "translate(-50%, -50%)",
                color: "white",
                fontWeight: "bold",
                // textShadow: "0 0 5px rgba(0,0,0,0.7)",
              }}
            >
              {room.title}
            </p>
          </div>

          <div className="approval-text">
            <div className="approval-info">
              <div className="approval-numberofpeople">스터디 정원</div>
              <div className="value">{displayMaxPeople}명</div>
            </div>
            <div className="approval-info">
              <div className="approval-purpose">목적</div>
              <div className="value">{displayPurpose}</div>
            </div>
            <div className="approval-info">
              <div className="approval-region">지역</div>
              <div className="value">{displayRegion}</div>
            </div>
          </div>

          <hr />

          <div className="approval-announcements">스터디 공지사항</div>
          <div className="approval-description">
            {room.description?.split("\n").map((line, idx) => (
              <p key={idx}>{line}</p>
            ))}
          </div>

          <div className="approval-buttons">
            <button
              className="approval-cancel-button"
              onClick={onClose}
              disabled={loading}
            >
              취소
            </button>
            <button
              className="approval-approval-button"
              onClick={(event) => {
                event.preventDefault();
                handleApprovalRequest();
              }}
              disabled={loading}
            >
              승인 요청
            </button>
          </div>
        </div>
      </div>

      {showSuccessModal && (
        <div className="success-modal-overlay">
          <div className="success-modal-content">
            <p>승인 요청이 완료되었습니다!</p>
            <button onClick={() => setShowSuccessModal(false)}>닫기</button>
          </div>
        </div>
      )}
    </>
  );
};

export default ApprovalRequestModal;