import React, { useEffect, useState } from "react";
import "../modals/MainAlarm.css";
import { Client } from "@stomp/stompjs";
import SockJS from "sockjs-client";


interface Notification {
  id: number;
  content: string;
  notificationType: string;
  url: string;
  createdAt: string;
  read: boolean;
}

const MainAlarm: React.FC = () => {
  const [notifications, setNotifications] = useState<Notification[]>([]);
  const [isOpen, setIsOpen] = useState(false);

  const userId = localStorage.getItem("userId");
  const token = localStorage.getItem("jwtToken");

  useEffect(() => {
    if (!userId || !token) return;

    // ✅ 1️⃣ 최초 알림 로드
    fetch(`http://34.64.218.29/api/notify/v1/notifications?userId=${userId}`, {
      headers: {
        Authorization: `Bearer ${token}`
      }
    })
      .then((res) => {
        if (!res.ok) {
          throw new Error("알림 로드 실패");
        }
        return res.json();
      })
      .then((data) => {
        // 👉 data.data 형식을 고려
        const notificationsData = data.data ?? data;
        setNotifications(notificationsData);
      })
      .catch((error) => {
        console.error(error);
      });

    // ✅ 2️⃣ STOMP 실시간 구독
    const stompClient = new Client({
      webSocketFactory: () =>
        new SockJS(`http://34.64.218.29/ws?token=${token}`),
      onConnect: () => {
        console.log("[STOMP] 실시간 알림 연결 성공");
        stompClient.subscribe(`/topic/user/${userId}`, (message) => {
          const received = JSON.parse(message.body) as Notification;
          setNotifications((prev) => [received, ...prev]);
        });
      },
      onStompError: (error) => {
        console.error("[STOMP 에러]", error);
      }
    });
    stompClient.activate();

    return () => {
      stompClient.deactivate();
    };
  }, [userId, token]);

  // ✅ 알림 메시지 포매팅
  const getNotificationMessage = (n: Notification): string => {
    switch (n.notificationType) {
      case "LOGIN":
        return "로그인되었습니다.";
      case "STUDY_CREATED":
        return "스터디방이 생성되었습니다.";
      case "STUDY_JOIN_REQUEST":
        return "스터디방 승인요청을 보냈습니다.";
      default:
        return n.content;
    }
  };
  
  // ✅ 알림 읽음 처리
  const markAsRead = async (notificationId: number) => {
    if (!token) return;

    try {
      await fetch(
        `http://34.64.218.29/api/notify/v1/notifications/${notificationId}/read`,
        {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            Authorization: `Bearer ${token}`
          }
        }
      );
      setNotifications((prev) =>
        prev.map((n) =>
          n.id === notificationId ? { ...n, read: true } : n
        )
      );
    } catch (error) {
      console.error(error);
    }
  };
  
  // ✅ 알림 전체 삭제
  const deleteAllNotifications = async () => {
    if (!token) return;

    try {
      await fetch(`http://34.64.218.29/api/notify/v1/notifications`, {
        method: "DELETE",
        headers: {
          Authorization: `Bearer ${token}`
        }
      });
      setNotifications([]);
    } catch (error) {
      console.error(error);
    }
  };
  
  return (
    <div className="main-alarm" onClick={() => setIsOpen(!isOpen)}>
      {isOpen && (
        <div className="alarm-modal">
          <h4>알림 목록</h4>
          
          <button
            className="main-alarm-button"
            onClick={(e) => {
              e.stopPropagation();
              deleteAllNotifications();
            }}
            style={{ marginBottom: "10px" }}
          >
            전체 삭제
          </button>

          <ul>
            {notifications.map((n) => (
              <li key={n.id}>
                <a href={n.url}>{getNotificationMessage(n)}</a>
                <span>{new Date(n.createdAt).toLocaleString()}</span>
                {!n.read && (
                  <button
                    onClick={(e) => {
                      e.stopPropagation();
                      markAsRead(n.id);
                    }}
                  >
                    읽음
                  </button>
                )}
              </li>
            ))}
          </ul>
        </div>
      )}
    </div>
  );
};

export default MainAlarm;