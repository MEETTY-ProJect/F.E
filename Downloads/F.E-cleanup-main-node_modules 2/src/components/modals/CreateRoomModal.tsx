import React, { useState, ChangeEvent } from 'react';
import axios from 'axios';
import studyroomImage from '../../assets/studyroom-image.jpg';


interface RoomData {
  id: number;
  roomName: string;
  hostName: string;
  introduction: string;
  capacity: number;
  currentMemberCount: number;
  purpose: string;
  region: string;
  imageUrl: string;
}

interface CreateRoomModalProps {
  isOpen: boolean;
  onClose: () => void;
  onCreateSuccess: (newRoomData: RoomData) => void;
}

interface CreateRoomResponse {
  isSuccess: boolean;
  data: RoomData;
  message?: string;
}

function CreateRoomModal({ isOpen, onClose, onCreateSuccess }: CreateRoomModalProps) {
  const [roomTitle, setRoomTitle] = useState('');
  const [roomDescription, setRoomDescription] = useState('');
  const [maxPeople, setMaxPeople] = useState('');
  const [purpose, setPurpose] = useState('전체');
  const [region, setRegion] = useState('전체');

  const DEFAULT_PROFILE_IMAGE = studyroomImage;
  const [selectedImage, setSelectedImage] = useState<string>(DEFAULT_PROFILE_IMAGE);
  const [selectedFile, setSelectedFile] = useState<File | null>(null);

  const options = Array.from({ length: 30 }, (_, i) => i + 1);
  const categories = ['전체', '학업/자격증', '취업/면접', '게임/프로그래밍', '자기계발'];
  const regions = [
    '전체', '서울특별시', '부산광역시', '인천광역시', '대전광역시',
    '경상남도', '경상북도', '전라남도', '전라북도',
    '충청남도', '충청북도', '강원도', '제주특별자치도',
  ];

  const purposeMap: { [key: string]: string } = {
    '학업/자격증': 'ACADEMIC_CERTIFICATE',
    '취업/면접': 'EMPLOYMENT_INTERVIEW',
    '게임/프로그래밍': 'DEVELOPMENT_PROGRAMMING',
    '자기계발': 'FOREIGN_LANGUAGE_SELF_IMPROVEMENT',
    '취미/예술': 'HOBBY_ART',
  };

  const regionMap: { [key: string]: string } = {
    전체: 'ETC',
    서울특별시: 'SEOUL',
    부산광역시: 'BUSAN',
    인천광역시: 'INCHEON',
    대전광역시: 'DAEJEON',
    경상남도: 'GYEONGSANGNAM',
    경상북도: 'GYEONGSANGBUK',
    전라남도: 'JEOLLANAM',
    전라북도: 'JEOLLABUK',
    충청남도: 'CHUNGCHEONNAM',
    충청북도: 'CHUNGCHEONBUK',
    강원도: 'GANGWON',
    제주특별자치도: 'JEJU',
  };

  const handleCancelCreate = () => {
    setRoomTitle('');
    setRoomDescription('');
    setMaxPeople('');
    setPurpose('전체');
    setRegion('전체');
    setSelectedImage(DEFAULT_PROFILE_IMAGE);
    setSelectedFile(null);
    onClose();
  };

  const handleImageChange = (e: ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;
    setSelectedFile(file);
    const reader = new FileReader();
    reader.onloadend = () => {
      setSelectedImage(reader.result as string);
    };
    reader.readAsDataURL(file);
  };

  const handleCreate = async () => {
    if (!roomTitle.trim() || !roomDescription.trim() || !maxPeople) {
      alert('필수 항목을 모두 입력해주세요.');
      return;
    }

    const capacityNum = parseInt(maxPeople.replace('명', ''), 10);
    if (isNaN(capacityNum) || capacityNum < 2) {
      alert('최소 인원은 2명 이상이어야 합니다.');
      return;
    }

    if (purpose === '전체') {
      alert('목적을 선택해주세요.');
      return;
    }

    if (region === '전체') {
      alert('지역을 선택해주세요.');
      return;
    }

    if (!selectedFile) {
      alert('이미지를 선택해주세요.');
      return;
    }

    const mappedPurpose = purposeMap[purpose];
    const mappedRegion = regionMap[region];

    const requestData = {
      roomName: roomTitle,
      introduction: roomDescription,
      capacity: capacityNum,
      purpose: mappedPurpose,
      region: mappedRegion,
    };

    const formData = new FormData();
    formData.append('request', JSON.stringify(requestData));
    formData.append('imageFile', selectedFile);

    try {
      const res = await axios.post<CreateRoomResponse>(
        'http://34.22.72.174:8080/api/v1/board/create',
        formData,
        {
          headers: {
            Authorization: `Bearer ${localStorage.getItem('accessToken') || ''}`,
            'Content-Type': 'multipart/form-data',
          },
          withCredentials: true,
        }
      );

      if (!res.data.isSuccess) {
        throw new Error(res.data.message || '스터디방 생성에 실패했습니다.');
      }

      onCreateSuccess(res.data.data);
      handleCancelCreate();
    } catch (error: any) {
      alert(`오류 발생: ${error.message}`);
      console.error(error);
    }
  };

  if (!isOpen) return null;

  return (
    <div className="create-overlay" onClick={onClose}>
      <div className="create-modal-content" onClick={(e) => e.stopPropagation()}>
        <div className="create-text">
          <h3>스터디 방 생성</h3>
          <div className="filter-line"></div>
        </div>

        <div className="create-roomtitle">
          스터디방 이름
          <input
            type="text"
            placeholder="스터디 방 이름을 입력하세요."
            value={roomTitle}
            onChange={(e) => setRoomTitle(e.target.value)}
          />
        </div>

        <div className="create-explanation">
          설명
          <textarea
            placeholder="스터디 방 설명 및 공지사항을 입력하세요"
            value={roomDescription}
            onChange={(e) => setRoomDescription(e.target.value)}
          />
        </div>

        <div className="Main-studyroom">스터디방 이미지</div>
        <div className="Main-studyroom-image">
          <img src={selectedImage} alt="스터디방 기본 이미지" className="studyroom-image" />
          <input
            type="file"
            accept="image/*"
            id="profile-image-upload"
            style={{ display: 'none' }}
            onChange={handleImageChange}
          />
          <button
            onClick={() => document.getElementById('profile-image-upload')?.click()}
            className="studyroom-image-select-button"
          >
            찾기
          </button>
        </div>

        <div className="maximum-people">최대 인원 수</div>
        <select
          className="peoplecount"
          value={maxPeople}
          onChange={(e) => setMaxPeople(e.target.value)}
        >
          <option value="">인원 선택</option>
          {options.map((num) => (
            <option key={num} value={`${num}명`}>
              {num}명
            </option>
          ))}
        </select>

        <div className="purpose-select">목적</div>
        <select
          className="purpose-category"
          value={purpose}
          onChange={(e) => setPurpose(e.target.value)}
        >
          {categories.map((cat) => (
            <option key={cat} value={cat}>
              {cat}
            </option>
          ))}
        </select>

        <div className="region-select">지역</div>
        <select
          className="region-category"
          value={region}
          onChange={(e) => setRegion(e.target.value)}
        >
          {regions.map((reg) => (
            <option key={reg} value={reg}>
              {reg}
            </option>
          ))}
        </select>

        <div className="create-buttons">
          <button className="create-buttons-cancel" onClick={handleCancelCreate}>
            취소
          </button>
          <button className="create-buttons-close" onClick={handleCreate}>
            생성
          </button>
        </div>
      </div>
    </div>
  );
}

export default CreateRoomModal;