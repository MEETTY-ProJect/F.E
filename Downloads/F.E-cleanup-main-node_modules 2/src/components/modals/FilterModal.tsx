import React, { useState, useEffect } from 'react';

interface FilterModalProps {
  isOpen: boolean; // true/false로 열림 상태 전달
  onClose: () => void; // 모달 닫기 함수
  onApplyFilter: (purpose: string, region: string) => void; // 필터 적용 함수
}

function FilterModal({ isOpen, onClose, onApplyFilter }: FilterModalProps) {
  const [selectedPurpose, setSelectedPurpose] = useState<string>('전체');
  const [selectedRegion, setSelectedRegion] = useState<string>('전체');

  // ⭐ 모달이 열릴 때마다 초기화
  useEffect(() => {
    if (isOpen) {
      setSelectedPurpose('전체');
      setSelectedRegion('전체');
    }
  }, [isOpen]);

  const handlePurposeClick = (item: string) => {
    setSelectedPurpose(item);
  };

  const handleRegionClick = (item: string) => {
    setSelectedRegion(item);
  };

  if (!isOpen) return null;

  return (
    <div className="filter-overlay" onClick={onClose}>
      <div className="filter-modal-content" onClick={(e) => e.stopPropagation()}>
        <div className="filter-text">목적</div>
        <div className="filter-line"></div>
        <div className="purpose-container">
          {["전체", "학업 / 자격증", "취업 / 면접", "개발 / 프로그래밍", "자기 계발"].map((item) => (
            <p
              key={item}
              onClick={() => handlePurposeClick(item)}
              className={selectedPurpose === item ? "selected" : ""}
            >
              {item}
            </p>
          ))}
        </div>

        <div className="filter-text">지역</div>
        <div className="filter-line"></div>
        <div className="purpose-container">
          {["전체", "서울", "부산광역시", "인천광역시", "대전광역시", "경상남도", "경상북도"].map((item) => (
            <p
              key={item}
              onClick={() => handleRegionClick(item)}
              className={selectedRegion === item ? "selected" : ""}
            >
              {item}
            </p>
          ))}
        </div>

        <div className="filter-buttons">
          <button className="filter-clear" onClick={onClose}>취소</button>
          <button
            className="filter-close"
            onClick={() => {
              onApplyFilter(selectedPurpose, selectedRegion);
              onClose();
            }}
          >
            확인
          </button>
        </div>
      </div>
    </div>
  );
}

export default FilterModal;